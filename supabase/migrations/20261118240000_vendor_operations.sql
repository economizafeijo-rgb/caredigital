grant execute on function public.care_store_customer_cancel(uuid) to authenticated;

-- Retirada no balcão: confere o código e entrega.
create or replace function public.care_store_redeem_pickup(p_vendor uuid, p_code text)
returns uuid language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_id uuid;
begin
  if not exists (select 1 from public.care_store_vendors where id = p_vendor and owner_id = auth.uid()) then
    raise exception 'Not your store';
  end if;
  select id into v_id from public.care_store_orders
   where vendor_id = p_vendor and pickup_code = upper(btrim(p_code)) and status in ('pago','separando','pronto','enviado');
  if v_id is null then raise exception 'Code not found or order not paid'; end if;
  update public.care_store_orders set status = 'entregue' where id = v_id;
  return v_id;
end;
$$;
revoke all on function public.care_store_redeem_pickup(uuid,text) from public, anon;
grant execute on function public.care_store_redeem_pickup(uuid,text) to authenticated;

