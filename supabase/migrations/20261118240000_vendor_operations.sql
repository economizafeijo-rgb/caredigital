-- Código de retirada sem caracteres ambíguos
create or replace function public.care_store_new_code()
returns text language sql volatile set search_path = public, pg_temp
as $$
  select string_agg(substr('ABCDEFGHJKMNPQRSTUVWXYZ23456789', 1 + floor(random() * 31)::int, 1), '')
  from generate_series(1, 6);
$$;

create or replace function public.care_store_order_before()
returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_vendor public.care_store_vendors%rowtype;
begin
  if tg_op = 'INSERT' then
    if new.vendor_id is not null and new.pickup_code is null then
      new.pickup_code := public.care_store_new_code();
    end if;
    return new;
  end if;
  if new.status is distinct from old.status then
    if old.status in ('entregue','cancelado') then
      raise exception 'Order already closed';
    end if;
    select * into v_vendor from public.care_store_vendors where id = new.vendor_id;
    if new.status = 'pago' and old.paid_at is null then
      new.paid_at := now();
      new.promised_at := now() + make_interval(mins => case when new.fulfillment = 'entrega'
        then coalesce(v_vendor.delivery_minutes, 120) else coalesce(v_vendor.prep_minutes, 30) end);
    end if;
    if new.status = 'pronto' then new.ready_at := coalesce(new.ready_at, now()); end if;
    if new.status = 'enviado' then new.shipped_at := coalesce(new.shipped_at, now()); end if;
    if new.status = 'entregue' then new.delivered_at := now(); end if;
    if new.status = 'cancelado' then new.cancelled_at := now(); end if;
    new.updated_at := now();
  end if;
  return new;
end;
$$;
drop trigger if exists care_store_orders_before on public.care_store_orders;
create trigger care_store_orders_before before insert or update on public.care_store_orders
  for each row execute function public.care_store_order_before();

create or replace function public.care_store_order_after()
returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_item jsonb; v_was_paid boolean;
begin
  if new.vendor_id is null then return null; end if;
  if tg_op = 'INSERT' then
    insert into public.care_store_order_events(order_id, vendor_id, status, note) values (new.id, new.vendor_id, new.status, 'Pedido recebido');
    return null;
  end if;
  if new.status is not distinct from old.status then return null; end if;
  insert into public.care_store_order_events(order_id, vendor_id, status) values (new.id, new.vendor_id, new.status);
  v_was_paid := old.paid_at is not null;
  -- Pagamento confirmado: entra a venda no caixa e sai a contribuição da plataforma.
  if new.paid_at is not null and not v_was_paid then
    insert into public.care_store_cash_entries(vendor_id, kind, amount_cents, category, description, order_id)
    values (new.vendor_id, 'entrada', new.total_cents, 'venda', 'Pedido #' || new.order_number, new.id);
    if new.commission_cents > 0 then
      insert into public.care_store_cash_entries(vendor_id, kind, amount_cents, category, description, order_id)
      values (new.vendor_id, 'saida', new.commission_cents, 'comissão NextVita', 'Contribuição do plano · pedido #' || new.order_number, new.id);
    end if;
  end if;
  -- Cancelamento: devolve o estoque e estorna o caixa se já estava pago.
  if new.status = 'cancelado' then
    perform set_config('nv.stock_reason', 'cancelamento', true);
    for v_item in select * from jsonb_array_elements(new.items) loop
      update public.care_store_products set stock = stock + coalesce((v_item ->> 'qty')::int, 0), updated_at = now()
       where id = (v_item ->> 'id')::uuid and vendor_id = new.vendor_id;
    end loop;
    perform set_config('nv.stock_reason', '', true);
    if v_was_paid then
      insert into public.care_store_cash_entries(vendor_id, kind, amount_cents, category, description, order_id)
      values (new.vendor_id, 'saida', new.total_cents, 'estorno', 'Cancelamento · pedido #' || new.order_number, new.id);
      if new.commission_cents > 0 then
        insert into public.care_store_cash_entries(vendor_id, kind, amount_cents, category, description, order_id)
        values (new.vendor_id, 'entrada', new.commission_cents, 'comissão NextVita', 'Comissão devolvida · pedido #' || new.order_number, new.id);
      end if;
    end if;
  end if;
  return null;
end;
$$;
drop trigger if exists care_store_orders_after on public.care_store_orders;
create trigger care_store_orders_after after insert or update on public.care_store_orders
  for each row execute function public.care_store_order_after();

-- Pedido: marca o motivo "venda" nos movimentos de estoque.
create or replace function public.care_store_place_order(
  p_vendor_id uuid, p_items jsonb, p_fulfillment text, p_name text, p_phone text,
  p_address text, p_payment text, p_notes text default null
) returns uuid
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_vendor public.care_store_vendors%rowtype;
  v_item jsonb;
  v_prod public.care_store_products%rowtype;
  v_qty integer;
  v_subtotal integer := 0;
  v_fee integer := 0;
  v_commission integer;
  v_lines jsonb := '[]'::jsonb;
  v_id uuid;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) not between 1 and 30 then
    raise exception 'Cart invalid';
  end if;
  if p_fulfillment not in ('entrega','retirada') or p_payment not in ('pix','cartao','boleto','dinheiro')
     or char_length(btrim(coalesce(p_name,''))) < 3
     or char_length(regexp_replace(coalesce(p_phone,''), '\D', '', 'g')) < 10 then
    raise exception 'Order fields invalid';
  end if;
  select * into v_vendor from public.care_store_vendors where id = p_vendor_id and status = 'ativo';
  if not found then raise exception 'Vendor unavailable'; end if;
  if p_fulfillment = 'entrega' and not v_vendor.offers_delivery then raise exception 'Delivery not offered'; end if;
  if p_fulfillment = 'retirada' and not v_vendor.offers_pickup then raise exception 'Pickup not offered'; end if;
  if p_fulfillment = 'entrega' and char_length(btrim(coalesce(p_address,''))) < 8 then raise exception 'Address required'; end if;

  perform set_config('nv.stock_reason', 'venda', true);
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item ->> 'qty')::integer;
    if v_qty is null or v_qty not between 1 and 20 then raise exception 'Quantity invalid'; end if;
    select * into v_prod from public.care_store_products
      where id = (v_item ->> 'product_id')::uuid and vendor_id = p_vendor_id and active for update;
    if not found then raise exception 'Product unavailable'; end if;
    if v_prod.stock < v_qty then raise exception 'Out of stock: %', v_prod.name; end if;
    update public.care_store_products set stock = stock - v_qty, updated_at = now() where id = v_prod.id;
    v_subtotal := v_subtotal + v_prod.price_cents * v_qty;
    v_lines := v_lines || jsonb_build_object('id', v_prod.id, 'name', v_prod.name, 'qty', v_qty, 'price_cents', v_prod.price_cents, 'image_url', v_prod.image_url);
  end loop;
  perform set_config('nv.stock_reason', '', true);

  if p_fulfillment = 'entrega' then
    v_fee := case when v_vendor.free_delivery_from_cents is not null and v_subtotal >= v_vendor.free_delivery_from_cents
                  then 0 else v_vendor.delivery_fee_cents end;
  end if;
  v_commission := round(v_subtotal * v_vendor.commission_bps / 10000.0)::integer;

  insert into public.care_store_orders(user_id, customer_name, customer_email, customer_phone, address, items, total_cents,
      payment_method, status, notes, vendor_id, fulfillment, delivery_fee_cents, commission_cents, vendor_net_cents)
  values (v_uid, btrim(p_name), nullif(lower(coalesce(auth.jwt() ->> 'email', '')), ''), btrim(p_phone),
      case when p_fulfillment = 'entrega' then btrim(p_address) else null end, v_lines, v_subtotal + v_fee,
      case when p_payment = 'dinheiro' then 'pix' else p_payment end, 'aguardando_pagamento',
      nullif(btrim(concat_ws(' · ', case when p_payment = 'dinheiro' then 'Pagar em dinheiro na retirada' end, nullif(btrim(coalesce(p_notes,'')), ''))), ''),
      v_vendor.id, p_fulfillment, v_fee, v_commission, v_subtotal + v_fee - v_commission)
  returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.care_store_place_order(uuid,jsonb,text,text,text,text,text,text) from public, anon;
grant execute on function public.care_store_place_order(uuid,jsonb,text,text,text,text,text,text) to authenticated;

-- Cliente cancela o próprio pedido enquanto não foi pago.
create or replace function public.care_store_customer_cancel(p_order uuid)
returns void language plpgsql security definer set search_path = public, pg_temp
as $$
begin
  update public.care_store_orders set status = 'cancelado'
   where id = p_order and user_id = auth.uid() and status = 'aguardando_pagamento';
  if not found then raise exception 'Order cannot be cancelled'; end if;
end;
$$;
