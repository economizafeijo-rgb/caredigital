create or replace function public.care_store_log_stock()
returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_reason text := coalesce(nullif(current_setting('nv.stock_reason', true), ''), 'ajuste');
begin
  if tg_op = 'INSERT' then
    if new.stock > 0 then
      insert into public.care_store_stock_moves(vendor_id, product_id, delta, stock_after, reason)
      values (new.vendor_id, new.id, new.stock, new.stock, 'estoque inicial');
    end if;
  elsif new.stock is distinct from old.stock then
    insert into public.care_store_stock_moves(vendor_id, product_id, delta, stock_after, reason)
    values (new.vendor_id, new.id, new.stock - old.stock, new.stock, v_reason);
  end if;
  return null;
end;
$$;
drop trigger if exists care_store_products_stock_log on public.care_store_products;
create trigger care_store_products_stock_log after insert or update of stock on public.care_store_products
  for each row execute function public.care_store_log_stock();

